export function Icon({
  name,
  size = 22,
  className,
  strokeWidth = 1.75,
}: {
  name?: string
  size?: number
  className?: string
  strokeWidth?: number
}) {
  const C = (name && MAP[name]) || MAP.default
  return <C size={size} strokeWidth={strokeWidth} className={className} aria-hidden />
}

